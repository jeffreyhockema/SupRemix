// Writes the original Supaplex level set into levels/pack.js.
// Run with `npm run import`.
//
// The decoding lives in tools/original.mjs; this is the part that applies our
// own changes on the way through and renders the file.
//
// Upgrades are the seam. `levels/upgrades.mjs` may export UPGRADES, a map of
// level number to a function that rewrites the level before it is written out
// -- that is where an original board is given keycards, boots, a pressure plate
// or anything else the original set had no vocabulary for. Nothing is edited in
// levels/pack.js itself: the next import overwrites it.

import { writeFileSync, existsSync } from 'node:fs';
import { readOriginal } from './original.mjs';
import { packGroup } from './pack-assets.mjs';

const OUT = 'levels/pack.js';

let upgrades = {};
if (existsSync('levels/upgrades.mjs')) {
  ({ UPGRADES: upgrades = {} } = await import('../levels/upgrades.mjs'));
}

const levels = [];
const changed = [];
for (const level of readOriginal()) {
  const patch = upgrades[level.n];
  if (!patch) { levels.push(level); continue; }
  const out = patch(structuredClone(level)) || level;
  out.n = level.n;
  levels.push(out);
  changed.push(`${level.n}. ${out.name}`);
}

/** What the level-select card says under the name. */
function describe(l) {
  const parts = [l.need ? `${l.need} infotrons.` : 'Every infotron on the board.'];
  if (l.gravity) parts.push('Gravity is on from the start.');
  return parts.join(' ');
}

const body = levels.map((l) => {
  const bits = [
    `    name: ${JSON.stringify(l.name)},`,
    `    hint: ${JSON.stringify(l.hint ?? describe(l))},`,
    `    w: ${l.w}, h: ${l.h},`,
  ];
  if (l.need) bits.push(`    need: ${l.need},`);
  if (l.gravity) bits.push('    gravity: true,');
  if (l.slimeCap != null) bits.push(`    slimeCap: ${l.slimeCap},`);
  bits.push(`    gate: ${JSON.stringify(l.gate ?? 'original')},`);
  bits.push('    rows: [');
  for (const r of l.rows) bits.push(`      ${JSON.stringify(r)},`);
  bits.push('    ],');
  if (l.floors) {
    bits.push('    floors: [');
    for (const r of l.floors) bits.push(`      ${JSON.stringify(r)},`);
    bits.push('    ],');
  }
  return [`  // ${'='.repeat(18)} ${l.n}. ${l.name}`, '  {', ...bits, '  },'].join('\n');
}).join('\n\n');

const header = `/*
 * SupRemix level pack -- the original Supaplex level set, all 111 boards.
 *
 * GENERATED by tools/import-original.mjs from levels/LEVELS.DAT. Do not edit
 * this file: the next import overwrites it. To change a level, add an entry to
 * levels/upgrades.mjs and run \`npm run import\`.
 *
 * The boards are the original designs, imported tile for tile. Levels are
 * written as INTERIOR rows only and the loader adds the chassis border, which
 * is exactly what the original has: the outer ring of all 111 is hardware.
 * \`npm run compare\` measures the result against the same LEVELS.DAT, so a
 * faithful import reads as identical on every axis.
 *
 * Legend -- objects
 *   (space) .  empty            #  chassis        %  chassis (green LED)
 *   &  chassis (red LED)        :  board          =  DIP chip
 *   [  ]  two-cell DIP, laid across    "  _  two-cell DIP, laid upright
 *   L  expansion slot           J  heatsink fin   K  socket slab
 *   M  Murphy                   O  capacitor      I  infotron      E  drive bay
 *   S  case fan                 e  short          B  bug           T  DIP switch
 *   o  orange floppy            y  yellow floppy  r  red floppy
 *   >  <  ^  v  ports           1 2 3 4  gravity ports (R D L U)
 *   |  -  +  vertical / horizontal / cross ports
 *   a c g p  jumper caps        A C G P  matching headers
 *   w  thermal boots            H  disk drive     *  electrolyte
 * Legend -- floors
 *   ~  data bus (ice)           @  pressure plate  ;  failing trace
 *   X  hot component            F  force field
 *
 * The last nine glyphs have no counterpart in the original set. They are what
 * levels/upgrades.mjs exists to add.
 */

`;

writeFileSync(OUT, `${header}const LEVELS = [\n${body}\n];\n\nmodule.exports = { LEVELS };\n`);
console.log(`${levels.length} original levels written to ${OUT}`);
packGroup('levels');
if (changed.length) console.log(`upgraded: ${changed.join(', ')}`);
